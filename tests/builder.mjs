import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(process.env.PETIT_TEST_TOOLS ? resolve(process.env.PETIT_TEST_TOOLS, 'package.json') : import.meta.url);
const { JSDOM } = require('jsdom');
const dom = new JSDOM(readFileSync(new URL('./admin-fixture.html', import.meta.url), 'utf8'), { url: 'https://example.test/wp-admin/', runScripts: 'outside-only' });
const { window: w } = dom;
const doc = w.document;
w.PetitPopularBuilder = { url: '/ajax', nonce: 'test-nonce', styles: 'https://example.test/popular.css' };
w.PetitPopularBuilder.defaults = Object.fromEntries([...doc.querySelectorAll('[data-pp]')].map(el => [el.dataset.pp, el.value]));
w.PetitPopularBuilder.saved = [];
let saved = new Map(), nextId = 300;
w.confirm = () => true;
let calls = [], clipboard = '', fail = false;
Object.defineProperty(w.navigator, 'clipboard', { value: { writeText: async text => { clipboard = text; } } });
w.fetch = async (url, options) => {
  calls.push({ url, options });
  if (options.body.get('action') === 'petit_popular_saved') {
    const body = options.body;
    const operation = body.get('operation');
    let data;
    const id = Number(body.get('id'));
    const listing = () => [...saved.values()].map(r => ({ id: r.id, name: r.name }));
    if (operation === 'save') {
      const args = { ...w.PetitPopularBuilder.defaults };
      for (const [key, value] of body.entries()) if (key.startsWith('args[')) args[key.slice(5, -1)] = value;
      const ranking = { id: id || nextId++, name: body.get('name'), args };
      saved.set(ranking.id, ranking);
      data = { ranking, saved: listing() };
    } else if (operation === 'load') data = saved.get(id);
    else if (operation === 'delete') { saved.delete(id); data = { saved: listing() }; }
    else if (operation === 'import') data = { id: 0, name: '', args: { ...w.PetitPopularBuilder.defaults, layout: 'vertical', period: '30d', title: 'Importat', radius: '11', gap: '19', accent: '#abc', show_image: 'no' } };
    return { ok: true, json: async () => ({ success: true, data }) };
  }
  return { ok: !fail, json: async () => fail ? { success: false, data: { message: 'Connexió no disponible' } } : { success: true, data: { html: '<section class="petit-popular">Vista nova</section>' } } };
};
const pause = () => new Promise(resolve => setTimeout(resolve, 430));
let checks = 0;
const check = (value, label) => { checks++; assert.ok(value, label); };
const change = (id, value) => { const el = doc.getElementById(id); el.value = value; el.dispatchEvent(new w.Event('change', { bubbles: true })); };
w.eval(readFileSync(new URL('../assets/builder.js', import.meta.url), 'utf8'));
check(doc.querySelectorAll('.pp-layout-choice').length === 4, 'Four visual layout selectors');
await pause();
check(calls.length === 1 && calls[0].options.body.get('mode') === 'demo', 'Initial demo preview');
check(doc.getElementById('pp-preview-frame').srcdoc.includes('Vista nova'), 'Response rendered into preview');
check(doc.getElementById('pp-preview-frame').getAttribute('sandbox') === 'allow-same-origin', 'Scripts disabled inside preview');
doc.querySelector('[data-layout="vertical"]').click();
check(doc.getElementById('pp-layout').value === 'vertical', 'Visual tile updates field');
check(doc.querySelector('[data-layout="vertical"]').getAttribute('aria-pressed') === 'true', 'Selected tile announced');
check(doc.getElementById('pp-columns').closest('p').hidden, 'Columns hidden for vertical layout');
check(!doc.getElementById('pp-image_position').closest('p').hidden, 'Image position visible');
change('pp-preview-width', '340px');
check(doc.getElementById('pp-preview-frame').style.width === '340px', 'Sidebar preview width');
change('pp-type', 'events');
check(!doc.getElementById('pp-event_period').closest('p').hidden, 'Event date controls visible');
change('pp-preview-mode', 'ranking');
await pause();
check(calls.at(-1).options.body.get('args[type]') === 'events' && calls.at(-1).options.body.get('mode') === 'ranking', 'Filters and real mode sent');
check(doc.getElementById('pp-preview-note').textContent.includes('no afegeix visites'), 'Real data context explained');
doc.getElementById('pp-copy').click();
await new Promise(resolve => setTimeout(resolve, 10));
check(clipboard.includes('layout="vertical"') && clipboard.includes('type="events"'), 'Copy action uses current shortcode');
check(doc.getElementById('pp-copy-status').textContent === 'Codi copiat!', 'Copy confirmed');
fail = true;
change('pp-title', 'Nova agenda');
await pause();
check(doc.getElementById('pp-preview-status').textContent === 'Connexió no disponible', 'Server error explained');
check(!doc.getElementById('pp-preview-frame').hasAttribute('srcdoc'), 'Failed preview does not display stale data');
check(doc.getElementById('pp-preview-frame').getAttribute('aria-busy') === 'false', 'Loading state cleared');
fail = false;
change('pp-type', 'posts');
check(!doc.getElementById('pp-post_months').closest('p').hidden, 'Publication window shown for news');
change('pp-type', 'events');
check(doc.getElementById('pp-post_months').closest('p').hidden, 'Publication window hidden for events');
change('pp-ranking-name', 'Rànquing de la portada');
doc.getElementById('pp-save').click();
await new Promise(resolve => setTimeout(resolve, 20));
check(doc.getElementById('pp-code').value === '[petit_popular id="300"]', 'Save produces stable shortcode');
check(doc.getElementById('pp-saved-select').options.length === 2, 'Saved ranking appears in library');
check(!doc.getElementById('pp-copy').disabled, 'Copy enabled after successful save');
change('pp-title', 'Canvi pendent');
check(doc.getElementById('pp-copy').disabled, 'Copy disabled while saved configuration has pending changes');
check(doc.getElementById('pp-save-status').textContent.includes('pendents'), 'Unsaved changes explained');
doc.getElementById('pp-save').click();
await new Promise(resolve => setTimeout(resolve, 20));
check(doc.getElementById('pp-code').value === '[petit_popular id="300"]' && saved.size === 1, 'Edit reuses ID rather than duplicating');
doc.getElementById('pp-new').click();
check(doc.getElementById('pp-ranking-name').value === '' && !doc.getElementById('pp-code').value.includes('id="300"'), 'New resets active ranking');
change('pp-saved-select', '300');
doc.getElementById('pp-load').click();
await new Promise(resolve => setTimeout(resolve, 20));
check(doc.getElementById('pp-title').value === 'Canvi pendent', 'Load restores saved fields');
change('pp-import-code', '[petit_popular period="30d" layout="vertical" title="Importat"]');
doc.getElementById('pp-import').click();
await new Promise(resolve => setTimeout(resolve, 20));
check(doc.getElementById('pp-layout').value === 'vertical' && doc.getElementById('pp-title').value === 'Importat', 'Legacy import repopulates visual builder');
check(doc.getElementById('pp-ranking-name').value === '' && !doc.getElementById('pp-code').value.includes('id="300"'), 'Legacy import is a new unsaved configuration');
check(doc.getElementById('pp-radius').value === '11' && doc.getElementById('pp-gap').value === '19', 'Legacy numeric appearance settings retained as custom choices');
check(doc.getElementById('pp-color-mode').value === 'custom' && doc.getElementById('pp-accent-picker').value === '#aabbcc', 'Legacy short hex color restored in visual picker');
change('pp-saved-select', '300');
doc.getElementById('pp-delete').click();
await new Promise(resolve => setTimeout(resolve, 20));
check(saved.size === 0 && doc.getElementById('pp-saved-select').options.length === 1, 'Delete updates library');
change('pp-show_image', 'no');
check(doc.getElementById('pp-image_position').closest('p').hidden, 'Photo position hidden in no-photo mode');
check(doc.getElementById('pp-code').value.includes('show_image="no"'), 'No-photo option included in shortcode');
change('pp-color-mode', 'custom');
change('pp-accent-picker', '#123456');
check(doc.getElementById('pp-code').value.includes('accent="#123456"'), 'Visual picker sets shortcode color');
change('pp-color-mode', 'brand');
check(!doc.getElementById('pp-code').value.includes('accent='), 'Brand color mode clears custom override');
check(doc.getElementById('pp-accent-picker').closest('p').hidden, 'Picker hidden while brand color used');
change('pp-radius', '16');
change('pp-gap', '24');
change('pp-rank_size', '40');
check(doc.getElementById('pp-code').value.includes('radius="16"') && doc.getElementById('pp-code').value.includes('gap="24"') && doc.getElementById('pp-code').value.includes('rank_size="40"'), 'Plain-language appearance choices produce expected settings');
w.close();
console.log(`PASS: ${checks} visual builder interaction checks`);
