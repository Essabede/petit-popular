import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(process.env.PETIT_TEST_TOOLS ? resolve(process.env.PETIT_TEST_TOOLS, 'package.json') : import.meta.url);
const { JSDOM } = require('jsdom');
const dom = new JSDOM(readFileSync(new URL('./admin-fixture.html', import.meta.url), 'utf8'), { url: 'https://example.test/wp-admin/', runScripts: 'outside-only' });
const { window: w } = dom;
const doc = w.document;
w.PetitPopularBuilder = { url: '/ajax', nonce: 'test-nonce', styles: 'https://example.test/popular.css' };
let calls = [], clipboard = '', fail = false;
Object.defineProperty(w.navigator, 'clipboard', { value: { writeText: async text => { clipboard = text; } } });
w.fetch = async (url, options) => {
  calls.push({ url, options });
  return { ok: !fail, json: async () => fail ? { success: false, data: { message: 'Connexió no disponible' } } : { success: true, data: { html: '<section class="petit-popular">Vista nova</section>' } } };
};
const pause = () => new Promise(resolve => setTimeout(resolve, 430));
let checks = 0;
const check = (value, label) => { checks++; assert.ok(value, label); };
const change = (id, value) => { const el = doc.getElementById(id); el.value = value; el.dispatchEvent(new w.Event('change', { bubbles: true })); };
w.eval(readFileSync(new URL('../assets/builder.js', import.meta.url), 'utf8'));
check(doc.querySelectorAll('.pp-layout-choice').length === 4, 'Four visual layout selectors');
await pause();
check(calls.length === 1 && calls[0].options.body.get('mode') === 'demo', 'Initial demo preview');
check(doc.getElementById('pp-preview-frame').srcdoc.includes('Vista nova'), 'Response rendered into preview');
check(doc.getElementById('pp-preview-frame').getAttribute('sandbox') === 'allow-same-origin', 'Scripts disabled inside preview');
doc.querySelector('[data-layout="vertical"]').click();
check(doc.getElementById('pp-layout').value === 'vertical', 'Visual tile updates field');
check(doc.querySelector('[data-layout="vertical"]').getAttribute('aria-pressed') === 'true', 'Selected tile announced');
check(doc.getElementById('pp-columns').closest('p').hidden, 'Columns hidden for vertical layout');
check(!doc.getElementById('pp-image_position').closest('p').hidden, 'Image position visible');
change('pp-preview-width', '340px');
check(doc.getElementById('pp-preview-frame').style.width === '340px', 'Sidebar preview width');
change('pp-type', 'events');
check(!doc.getElementById('pp-event_period').closest('p').hidden, 'Event date controls visible');
change('pp-preview-mode', 'ranking');
await pause();
check(calls.at(-1).options.body.get('args[type]') === 'events' && calls.at(-1).options.body.get('mode') === 'ranking', 'Filters and real mode sent');
check(doc.getElementById('pp-preview-note').textContent.includes('no afegeix visites'), 'Real data context explained');
doc.getElementById('pp-copy').click();
await new Promise(resolve => setTimeout(resolve, 10));
check(clipboard.includes('layout="vertical"') && clipboard.includes('type="events"'), 'Copy action uses current shortcode');
check(doc.getElementById('pp-copy-status').textContent === 'Codi copiat!', 'Copy confirmed');
fail = true;
change('pp-title', 'Nova agenda');
await pause();
check(doc.getElementById('pp-preview-status').textContent === 'Connexió no disponible', 'Server error explained');
check(!doc.getElementById('pp-preview-frame').hasAttribute('srcdoc'), 'Failed preview does not display stale data');
check(doc.getElementById('pp-preview-frame').getAttribute('aria-busy') === 'false', 'Loading state cleared');
w.close();
console.log(`PASS: ${checks} visual builder interaction checks`);
